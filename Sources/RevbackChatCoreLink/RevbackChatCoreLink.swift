// Таргет-заглушка без кода: весь его смысл — в `linkerSettings: [.linkedLibrary("sqlite3")]`
// в манифесте пакета.
//
// Зачем он нужен. Ядро `RevbackChatCore` приезжает бинарным XCFramework (Kotlin/Native,
// статический архив), кэш беседы у него на SQLDelight/SQLiter: в бинарнике 30 неразрешённых
// символов `sqlite3_*` и ни одной autolink-подсказки `-lsqlite3` — статический архив их не несёт.
// У продукта с готовым экраном системную libsqlite3 подтягивает таргет `RevbackChatUI`, а у
// продукта «только ядро» (для тех, кто рисует экран сам) без этого таргета подтягивать нечему: там
// один `binaryTarget`, а настройки линковщика бинарный таргет нести не умеет. Линковка приложения
// такого интегратора падала бы на символах `sqlite3_*`. Этот таргет и есть недостающее место,
// куда настройку можно положить.
//
// Трогать содержимое файла не нужно. Убрать таргет из продукта `RevbackChatCore` нельзя —
// вместе с ним из продукта уйдёт `-lsqlite3`, а манифест уезжает в неизменяемый git-тег
// публичного репозитория: после релиза это не переиграть.

/// Пустой маркер — чтобы модуль не оказался пустой единицей трансляции.
/// Полезной нагрузки нет: всю работу таргета делает манифест пакета.
enum RevbackChatCoreLinkMarker {
    static let reason = "linkedLibrary(\"sqlite3\") для продукта RevbackChatCore"
}
